pub(super) fn glyph(key: &str) -> Option<&'static Path> {
    static ANTIGRAVITY_GLYPH: LazyLock<PathBuf> =
        LazyLock::new(|| icons::bundle("ai-account-antigravity", ANTIGRAVITY));
    static OPENAI_GLYPH: LazyLock<PathBuf> =
        LazyLock::new(|| icons::bundle("ai-account-openai", OPENAI));
    static GEMINI_GLYPH: LazyLock<PathBuf> =
        LazyLock::new(|| icons::bundle("ai-account-gemini", GEMINI));
    static COPILOT_GLYPH: LazyLock<PathBuf> =
        LazyLock::new(|| icons::bundle("ai-account-copilot", COPILOT));
    Some(match key {
        "ai-claude" => harness::glyph(Source::Claude),
        "ai-antigravity" => ANTIGRAVITY_GLYPH.as_path(),
        "ai-openai" => OPENAI_GLYPH.as_path(),
        "ai-google" => GEMINI_GLYPH.as_path(),
        "ai-github" => COPILOT_GLYPH.as_path(),
        _ => return None,
    })
}
